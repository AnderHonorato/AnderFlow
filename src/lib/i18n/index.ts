export type LangKey = keyof typeof translations
export type TransKey = keyof typeof translations['pt-BR']

export function t(key: string, lang: string = 'pt-BR'): string {
  const locale = (translations[lang as LangKey] || translations['pt-BR']) as Record<string, string>
  return locale[key] || key
}

export function getGreeting(lang: string = 'pt-BR'): string {
  const hour = new Date().getHours()
  if (lang === 'en') {
    if (hour < 12) return 'Good morning'
    if (hour < 18) return 'Good afternoon'
    return 'Good evening'
  }
  if (hour < 6) return 'Boa noite'
  if (hour < 12) return 'Bom dia'
  if (hour < 18) return 'Boa tarde'
  return 'Boa noite'
}
